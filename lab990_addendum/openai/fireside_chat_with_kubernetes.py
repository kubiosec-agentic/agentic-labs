def get_kubernetes_pods(logger, namespace, pod_status=""):
    cmd = ["kubectl", "get", "pods", "-n", namespace, "-o", "json"]
    try:
        log_kubectl_command(logger, cmd, namespace,
                           function_name="get_kubernetes_pods")
        result = subprocess.run(cmd, capture_output=True, text=True,
                                check=True)
        return (f"kubectl get pods output for namespace "
                f"'{namespace}':\n{result.stdout}")
    except subprocess.CalledProcessError as e:
        log_kubectl_command(logger, cmd, namespace,
                           function_name="get_kubernetes_pods",
                           success=False, error_msg=str(e.stderr))
        return f"Error running kubectl: {e.stderr}"
    except Exception as e:
        log_kubectl_command(logger, cmd, namespace,
                           function_name="get_kubernetes_pods",
                           success=False, error_msg=str(e))
        return f"Error: {e}"


