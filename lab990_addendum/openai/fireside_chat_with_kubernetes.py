# ---- Logging -----------------------------------------------------------

def setup_logging():
    """Set up logging for kubectl command auditing."""
    log_dir = "kubectl_audit_logs"
    if not os.path.exists(log_dir):
        os.makedirs(log_dir)

    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    log_filename = f"{log_dir}/kubectl_audit_{timestamp}.log"

    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(levelname)s - %(message)s",
        handlers=[
            logging.FileHandler(log_filename),
            logging.StreamHandler(),
        ],
    )

    logger = logging.getLogger(__name__)
    logger.info("=== Starting Kubernetes Assistant Session ===")
    logger.info("Log file: %s", log_filename)
    return logger


def log_kubectl_command(logger, cmd, namespace=None, function_name=None,
                        success=True, error_msg=None):
    """Log kubectl command execution for auditing."""
    log_entry = {
        "timestamp": datetime.datetime.now().isoformat(),
        "function": function_name,
        "command": " ".join(cmd),
        "namespace": namespace,
        "success": success,
        "user": os.getenv("USER", "unknown"),
        "pwd": os.getcwd(),
    }
    if error_msg:
        log_entry["error"] = error_msg

    if success:
        logger.info("KUBECTL_SUCCESS: %s", json.dumps(log_entry))
    else:
        logger.error("KUBECTL_ERROR: %s", json.dumps(log_entry))


# ---- Kubectl check -----------------------------------------------------

def check_kubectl():
    """Return (True, msg) if kubectl is available, (False, msg) otherwise."""
    try:
        subprocess.run(["kubectl", "version", "--client"],
                       capture_output=True, check=True)
        return True, "kubectl is available"
    except (subprocess.CalledProcessError, FileNotFoundError):
        return False, "kubectl is not installed or not in PATH"


