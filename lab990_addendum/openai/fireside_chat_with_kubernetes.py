def execute_kubectl_command(logger, kubectl_args, description):
    cmd = ["kubectl"] + kubectl_args
    cmd_str = " ".join(cmd)
    try:
        print(f"\n  SECURITY CONFIRMATION REQUIRED")
        print(f"  Command:     {cmd_str}")
        print(f"  Description: {description}")
        confirmation = input(
            "  Execute this command? [Y/n] (Enter = Yes): "
        ).strip().lower()

        logger.info("KUBECTL_CONFIRMATION_REQUESTED: %s",
                     json.dumps({"command": cmd_str,
                                 "description": description,
                                 "user": os.getenv("USER", "unknown")}))

        if confirmation in ("n", "no"):
            logger.info("KUBECTL_DENIED: %s",
                         json.dumps({"command": cmd_str,
                                     "user": os.getenv("USER", "unknown")}))
            return f"Command execution denied by user: {cmd_str}"

        logger.info("KUBECTL_APPROVED: %s",
                     json.dumps({"command": cmd_str,
                                 "user": os.getenv("USER", "unknown")}))

        log_kubectl_command(logger, cmd,
                           function_name="execute_kubectl_command")
        result = subprocess.run(cmd, capture_output=True, text=True,
                                check=True)
        return f"kubectl output:\nCommand: {cmd_str}\n\n{result.stdout}"
    except subprocess.CalledProcessError as e:
        log_kubectl_command(logger, cmd,
                           function_name="execute_kubectl_command",
                           success=False, error_msg=str(e.stderr))
        return f"Error running kubectl command: {e.stderr}"
    except Exception as e:
        log_kubectl_command(logger, cmd,
                           function_name="execute_kubectl_command",
                           success=False, error_msg=str(e))
        return f"Error: {e}"


