def interactive_kubernetes_assistant():
    """Interactive Kubernetes assistant that runs real kubectl commands."""
    logger = setup_logging()

    if not os.getenv("OPENAI_API_KEY"):
        print("ERROR: OPENAI_API_KEY environment variable is not set.")
        print("Run: export OPENAI_API_KEY='your-key-here'")
        logger.error("OPENAI_API_KEY not set")
        return

    kubectl_available, kubectl_msg = check_kubectl()
    if not kubectl_available:
        print(f"ERROR: {kubectl_msg}")
        print("Install kubectl and configure it for your cluster.")
        logger.error("kubectl not available: %s", kubectl_msg)
        return

    print("Interactive Kubernetes Assistant")
    print("=" * 50)
    print(f"  {kubectl_msg}")
    print("Ask about pods, logs, or any Kubernetes operations.")
    print("Type 'quit' to exit.\n")
    logger.info("Interactive Kubernetes Assistant started")

    client = OpenAI()  # reads OPENAI_API_KEY and OPENAI_BASE_URL from env

    function_map = {
        "get_kubernetes_pods": lambda **kw: get_kubernetes_pods(logger, **kw),
        "get_pod_logs": lambda **kw: get_pod_logs(logger, **kw),
        "describe_pod": lambda **kw: describe_pod(logger, **kw),
        "execute_kubectl_command": lambda **kw: execute_kubectl_command(logger, **kw),
    }

    conversation_history = [
        {
            "role": "system",
            "content": (
                "You are a helpful DevOps assistant that interacts with "
                "Kubernetes clusters using kubectl commands. You can get "
                "pod information, logs, and descriptions. Always provide "
                "clear explanations. Remember previous interactions in "
                "this conversation."
            ),
        },
    ]

    while True:
        try:
            user_input = input(
                "\nWhat would you like to know about your cluster? "
            )

            if user_input.lower() in ("quit", "exit", "q"):
                print("Goodbye.")
                logger.info("=== Session Ended ===")
                break

            if not user_input.strip():
                continue

            logger.info("USER_INPUT: %s", user_input)
            conversation_history.append(
                {"role": "user", "content": user_input}
            )

            # Step 1: model decides which tool(s) to call
            response = client.chat.completions.create(
                model="gpt-4o",
                messages=conversation_history,
                tools=TOOLS,
                tool_choice="auto",
            )

            message = response.choices[0].message

            if message.tool_calls:
                n = len(message.tool_calls)
                print(f"\n[tool] Running {n} kubectl "
                      f"command{'s' if n > 1 else ''}...")

                conversation_history.append({
                    "role": "assistant",
                    "content": message.content,
                    "tool_calls": message.tool_calls,
                })

                # Step 2: execute every tool call
                for i, tool_call in enumerate(message.tool_calls):
                    fn_name = tool_call.function.name
                    args = json.loads(tool_call.function.arguments)

                    if n > 1:
                        print(f"  [{i + 1}/{n}] {fn_name}")

                    if fn_name in function_map:
                        output = function_map[fn_name](**args)
                    else:
                        output = f"Unknown function: {fn_name}"
                        logger.error("UNKNOWN_FUNCTION: %s", fn_name)

                    conversation_history.append({
                        "role": "tool",
                        "tool_call_id": tool_call.id,
                        "content": output,
                    })

                # Step 3: model summarises the results
                follow_up = client.chat.completions.create(
                    model="gpt-4o",
                    messages=conversation_history,
                )

                final = follow_up.choices[0].message.content
                print(f"\n{final}")
                conversation_history.append(
                    {"role": "assistant", "content": final}
                )

            else:
                text = message.content
                print(f"\n{text}")
                conversation_history.append(
                    {"role": "assistant", "content": text}
                )

        except KeyboardInterrupt:
            print("\nGoodbye.")
            logger.info("=== Session interrupted (Ctrl+C) ===")
            break
        except Exception as e:
            print(f"\nError: {e}")
            logger.error("GENERAL_ERROR: %s", e)


if __name__ == "__main__":
    interactive_kubernetes_assistant()
