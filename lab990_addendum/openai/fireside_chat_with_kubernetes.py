"""
Interactive Kubernetes assistant using OpenAI function calling.

The LLM decides which kubectl command to run, the tool executes it locally,
and the model summarises the output.  Every kubectl invocation is logged to
an audit file under kubectl_audit_logs/.

Supports OPENAI_BASE_URL override (useful with mitmproxy).

Generated by Copilot, cleaned for lab use.
"""

